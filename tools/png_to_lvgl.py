#!/usr/bin/env python3
"""Convert an 8-bit RGB/RGBA PNG to an LVGL 9 image C file.

usage: png_to_lvgl.py <in.png> <a8|rgb565> <symbol_name>   (writes C to stdout)

a8:     alpha channel only, for single-color icons recolored at runtime.
rgb565: opaque color image, native little-endian (the TFT_eSPI driver swaps bytes on push).
"""
import os
import struct
import sys
import zlib


def load_png(path):
    data = open(path, "rb").read()
    pos, idat = 8, b""
    while pos < len(data):
        (length,) = struct.unpack(">I", data[pos:pos + 4])
        kind = data[pos + 4:pos + 8]
        chunk = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            w, h, depth, color_type = struct.unpack(">IIBB", chunk[:10])
        elif kind == b"IDAT":
            idat += chunk
    if depth != 8 or color_type not in (2, 6):
        sys.exit(f"{path}: need 8-bit RGB or RGBA (got depth {depth}, color type {color_type})")

    bpp = 4 if color_type == 6 else 3
    stride = w * bpp
    raw = zlib.decompress(idat)
    rows, prev, i = [], bytearray(stride), 0
    for _ in range(h):
        flt = raw[i]
        line = bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if flt == 1:
                line[x] = (line[x] + a) & 255
            elif flt == 2:
                line[x] = (line[x] + b) & 255
            elif flt == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif flt == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append([tuple(line[x * bpp:x * bpp + bpp]) + ((255,) if bpp == 3 else ()) for x in range(w)])
        prev = line
    return w, h, rows


def main():
    if len(sys.argv) != 4 or sys.argv[2] not in ("a8", "rgb565"):
        sys.exit(__doc__)
    path, fmt, name = sys.argv[1:]
    w, h, rows = load_png(path)

    out = bytearray()
    for row in rows:
        for r, g, b, a in row:
            if fmt == "a8":
                out.append(a)
            else:
                out += struct.pack("<H", ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))

    cf, stride = ("LV_COLOR_FORMAT_A8", w) if fmt == "a8" else ("LV_COLOR_FORMAT_RGB565", w * 2)
    print(f"// Generated by tools/png_to_lvgl.py from {os.path.basename(path)}. Do not edit.")
    print("#include <lvgl.h>\n")
    print(f"static const uint8_t {name}_map[] = {{")
    for i in range(0, len(out), 24):
        print("    " + ", ".join(f"0x{v:02x}" for v in out[i:i + 24]) + ",")
    print("};\n")
    print(f"const lv_image_dsc_t {name} = {{")
    print(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = {cf}, .w = {w}, .h = {h}, .stride = {stride}}},")
    print(f"    .data_size = sizeof({name}_map),")
    print(f"    .data = {name}_map,")
    print("};")


main()

#!/usr/bin/env python3
"""Make the small Noto fonts that fill in characters Grift doesn't have.

usage: subset_noto.py <NotoSans[wdth,wght].ttf> <NotoSansJP[wght].ttf>

Downloads come from github.com/google/fonts (ofl/notosans, ofl/notosansjp). Writes static SemiBold and
Medium instances to design/fonts/, cut down to the characters in WANTED that Grift lacks (Noto Sans
first, Noto Sans JP for what's left), so they stay small enough to commit, and writes the exact
character ranges each font contributes to tools/font_ranges.sh (lv_font_conv rejects a range a font
has nothing in). gen_assets.sh turns them into the fallback fonts. Needs fonttools
(pip install fonttools). Run it again after changing WANTED.
"""
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "design" / "fonts"

WANTED = [
    (0x0100, 0x017F),  # Latin Extended-A: Central European, Turkish, Baltic…
    (0x01A0, 0x01A1), (0x01AF, 0x01B0),  # Vietnamese Ơ ơ Ư ư
    (0x0218, 0x021B),  # Romanian Ș ș Ț ț
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x045F), (0x0490, 0x0491),  # Cyrillic: Russian, Ukrainian, Bulgarian, Serbian…
    (0x1EA0, 0x1EF9),  # Vietnamese
    (0x2010, 0x2027), (0x2030, 0x203A),  # punctuation (‰, ‹ ›, •)
    (0x20AC, 0x20AC), (0x2122, 0x2122),  # € ™
    (0x2605, 0x2606), (0x2661, 0x2661), (0x2665, 0x2665), (0x266A, 0x266B),  # ★ ☆ ♡ ♥ ♪ ♫
    (0x3000, 0x303F),  # CJK punctuation (、。「」)
    (0x3041, 0x3096), (0x3099, 0x30FF),  # hiragana, katakana
    (0xFF01, 0xFF60),  # full-width forms
]
# Grift has a few Greek letters (Δ Ω μ π); Greek text reads better all in Noto.
NOT_FROM_GRIFT = set(range(0x0370, 0x0400))
WEIGHTS = {"SemiBold": 600, "Medium": 500}


def wanted():
    return {c for lo, hi in WANTED for c in range(lo, hi + 1)}


def cmap(font):
    return set(font.getBestCmap())


def make(source, weight, codepoints, out):
    font = TTFont(source)
    axes = {"wght": weight}
    if "wdth" in [a.axisTag for a in font["fvar"].axes]:
        axes["wdth"] = 100
    font = instancer.instantiateVariableFont(font, axes)
    options = subset.Options()
    options.layout_features = []  # lv_font_conv only uses the glyphs
    options.name_IDs = ["*"]  # keep the copyright and license notices
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(codepoints))
    subsetter.subset(font)
    font.save(out)
    return cmap(font)


def ranges(codepoints):
    """"0x100-0x17F,0x218" style, as lv_font_conv takes them."""
    out, run = [], []
    for c in sorted(codepoints):
        if run and c != run[-1] + 1:
            out.append(run)
            run = []
        run.append(c)
    if run:
        out.append(run)
    return ",".join(f"0x{r[0]:X}" if len(r) == 1 else f"0x{r[0]:X}-0x{r[-1]:X}" for r in out)


def main():
    noto, noto_jp = sys.argv[1:3]
    lines = ["# Generated by tools/subset_noto.py: the characters each font adds beyond Grift's base range.",
             "# shellcheck disable=SC2034"]
    for name, weight in WEIGHTS.items():
        grift = cmap(TTFont(FONTS / f"Grift-{name}.otf")) - NOT_FROM_GRIFT
        missing = wanted() - grift
        got = make(noto, weight, missing & cmap(TTFont(noto)), FONTS / f"NotoSans-{name}-subset.ttf")
        got_jp = make(noto_jp, weight, (missing - got) & cmap(TTFont(noto_jp)),
                      FONTS / f"NotoSansJP-{name}-subset.ttf")
        lines += [f"grift_extra_{name}={ranges(wanted() & grift)}",
                  f"noto_{name}={ranges(got)}",
                  f"noto_jp_{name}={ranges(got_jp)}"]
        print(f"{name}: {len(got)} from Noto Sans, {len(got_jp)} from Noto Sans JP, "
              f"{len(missing - got - got_jp)} not in either")
    (ROOT / "tools" / "font_ranges.sh").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()

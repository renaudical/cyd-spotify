#!/usr/bin/env python3
"""Writes src/net/tz_table.cpp: IANA zone name -> POSIX TZ string, from the system's zoneinfo.

Each TZif v2+ file ends with "\n<POSIX TZ string>\n", the rule for times after its last transition,
which is what the ESP32's newlib needs. Rerun when the system tz database is updated.
Usage: python3 -I tools/gen_timezones.py [zoneinfo dir] > src/net/tz_table.cpp
"""
import pathlib
import sys

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo")
REGIONS = ["Africa", "America", "Antarctica", "Arctic", "Asia", "Atlantic", "Australia", "Europe",
           "Indian", "Pacific", "Etc"]


def footer(path):
    data = path.read_bytes()
    if not data.startswith(b"TZif") or data[4:5] < b"2":
        return None
    rule = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
    return rule or None


zones = {}
for region in REGIONS:
    for path in sorted((ROOT / region).rglob("*")):
        if path.is_file() and (rule := footer(path)):
            zones[path.relative_to(ROOT).as_posix()] = rule
zones["UTC"] = "UTC0"

version = (ROOT / "+VERSION").read_text().strip() if (ROOT / "+VERSION").exists() else "unknown"
print(f"// Generated by tools/gen_timezones.py from tz database {version}. Don't edit by hand.")
print('#include "timezones.h"\n')
print("namespace tz {\n")
print("// Sorted by name for binary search.")
print("const Zone kZones[] = {")
for name in sorted(zones):
    print(f'    {{"{name}", "{zones[name]}"}},')
print("};")
print(f"const size_t kZoneCount = {len(zones)};\n")
print("}  // namespace tz")
